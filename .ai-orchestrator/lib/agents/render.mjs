// Builds the agent files and the shared rules file (agent-roster spec 2.1, 2.6) from agents/roster.yaml, the
// hand-written prompts and rules, the contract, quality/gates.yaml and tracker/jira.yaml. Pure: scripts/render-agents.mjs
// reads the sources and writes the result.
// sources: { roster, contract, gates, mapping, prompts: { role: text }, rules: text, space? }. space is the key of the
// Jira space; the kit leaves <KEY>.

const BASE_TOOLS = ['Read', 'Glob', 'Grep'];

export function renderAgent(role, sources) {
  const { roster, contract, prompts } = sources;
  const entry = roster.roles[role];
  const name = contract.roles.find(({ id }) => id === role).name;
  const agentValue = agentValues(contract)[role];
  const lines = [
    '---',
    `# Generated by scripts/render-agents.mjs from agents/roster.yaml, agents/prompts/${role}.md and the contract. Do not edit.`,
    `name: ${role}`,
    `description: ${JSON.stringify(entry.description)}`,
    `tools: ${tools(entry, roster).join(', ')}`,
    `model: ${entry.model}`,
    `effort: ${entry.effort}`,
    ...(entry.max_turns ? [`maxTurns: ${entry.max_turns}`] : []),
    ...(entry.skills.length > 0 ? ['skills:', ...entry.skills.map((skill) => `  - ${skill}`)] : []),
    '---',
    '',
    `You are \`${role}\`, the ${name} of the SDLC contract. Your value in the Agent field of Jira is "${agentValue}".`,
    '',
    '## Contract',
    '',
    ...contractLines(role, sources),
    '',
    stripComments(prompts[role]),
  ];
  return finish(lines.join('\n'));
}

export function renderRules(sources) {
  const parts = {
    jira: () => jiraPart(sources),
    agents: () => table(['Role', 'Agent field'], Object.entries(agentValues(sources.contract)).map(([role, value]) => [`\`${role}\``, value])),
    retry: () => `- When the same step fails ${sources.contract.retry.agent_failures_before_stop} times in a row, flag the item "Needs you" and stop.`,
    branches: () => branchesPart(sources),
    artifacts: () => artifactsPart(sources.contract),
    protected: () => sources.gates.protected_paths.map(({ path, editors }) => `  - \`${path}\`: ${editors ? `only ${editors.map(code).join(', ')}` : 'no agent'}`).join('\n'),
  };
  const body = stripComments(sources.rules).replace(/^<!-- render: ([\w-]+) -->$/gm, (marker, part) => {
    if (!parts[part]) throw new Error(`agents/rules.md: unknown render part '${part}'`);
    return parts[part]();
  });
  return finish(`<!-- Generated by scripts/render-agents.mjs from agents/rules.md and the contract. Do not edit. -->\n\n${body}`);
}

// Every generated file, by its path under .claude/.
export function renderAll(sources) {
  const files = new Map(Object.keys(sources.roster.roles).map((role) => [`agents/${role}.md`, renderAgent(role, sources)]));
  files.set('rules/ai-orchestrator.md', renderRules(sources));
  return files;
}

// Read, Glob and Grep, the role's own tools, then its Jira tools and MCP tools in roster order.
function tools(entry, roster) {
  const jira = [...new Set(entry.jira.flatMap((permission) => roster.jira_tools[permission]))].map((tool) => `mcp__atlassian__${tool}`);
  const mcp = Object.entries(entry.mcp ?? {}).flatMap(([server, groups]) => groups.flatMap((group) => roster.mcp_tools[server][group].map((tool) => `mcp__${server}__${tool}`)));
  return [...BASE_TOOLS, ...entry.tools, ...jira, ...mcp];
}

function contractLines(role, { roster, contract, gates, mapping }) {
  const entry = roster.roles[role];
  const lines = contract.stages.filter(({ roles }) => roles.includes(role)).map((stage) => stageLine(role, stage, contract));
  for (const artifact of contract.artifacts.filter(({ created_by: by }) => Array.isArray(by) && by.includes(role))) {
    lines.push(`- You create ${artifact.name} (\`${artifact.id}\`) from \`.ai-orchestrator/${artifact.template}\`, stored in ${stored(artifact.stored_in)}.`);
  }
  lines.push(`- Jira: ${entry.jira.join(', ')}.`);
  if (entry.jira.includes('transition')) lines.push(`- Transitions you make: ${transitionsOf(role, contract, mapping)}.`);
  const app = Object.entries(gates.github_apps).find(([, { roles }]) => roles.includes(role));
  if (app) {
    const [kind, { env, commands }] = app;
    const command = commands.length === 1 ? `\`node .ai-orchestrator/scripts/ao-pr.mjs ${commands[0]}\`` : `\`node .ai-orchestrator/scripts/ao-pr.mjs <command>\`, with <command> one of ${commands.join(', ')},`;
    lines.push(`- GitHub: ${command} with the ${kind} App (\`${env}\`). You never approve a PR.`);
  } else lines.push('- GitHub: you have no App, so you do not open or comment on PRs.');
  lines.push(`- Files you may write: ${filesText(role, entry, gates)}. Git: ${entry.git === 'read' ? 'read only (status, log, show, diff, fetch and the other reading commands)' : 'write'}.`);
  return lines;
}

function stageLine(role, stage, contract) {
  const others = stage.roles.filter((r) => r !== role).map((r) => (r === 'human' ? 'the human' : r === 'automation' ? 'automation' : code(r)));
  const outputs = stage.outputs.artifacts?.map((id) => contract.artifacts.find((a) => a.id === id).name).join(', ') ?? stage.outputs.other;
  const gate = stage.gate && contract.gates.find(({ id }) => id === stage.gate);
  const passes = [stage.exit, gate && `gate ${circled(gate.number)} ${code(gate.id)}: ${gate.description}`].filter(Boolean).join('; ');
  return [
    `- Stage ${code(stage.id)} (${stage.name})${stage.lead === role ? ', which you lead' : ''}${others.length > 0 ? `, with ${and(others)}` : ''}.`,
    `Input: ${stage.input}.`,
    `Output: ${outputs}.`,
    `Passes: ${passes}.`,
    ...(stage.note ? [`Note: ${stage.note}.`] : []),
  ].join(' ');
}

// The transitions the role is an actor of, by workflow, with their names and states on Jira.
function transitionsOf(role, contract, mapping) {
  const groups = [];
  for (const [id, workflow] of Object.entries(contract.workflows)) {
    const jira = mapping.workflows[id];
    const mine = workflow.transitions.filter(({ actors }) => actors.includes(role));
    if (mine.length === 0) continue;
    const text = mine.map((t) => {
      const from = [t.from].flat().map((state) => jira.states[state].status).join(', ');
      return `${code(t.id)} (${jira.transitions[t.id].name}: ${from} → ${jira.states[t.to].status})`;
    });
    groups.push(`${id}: ${text.join(', ')}`);
  }
  return groups.join('; ');
}

function filesText(role, entry, gates) {
  const globs = entry.writes.map(code).join(', ') || 'none';
  if (!entry.writes.includes('**')) return globs;
  const editable = gates.protected_paths.filter(({ editors }) => editors?.includes(role)).map(({ path }) => code(path));
  return `${globs}, but not the protected paths${editable.length > 0 ? ` except ${editable.join(', ')}` : ''}`;
}

function jiraPart({ mapping, space = '<KEY>' }) {
  return `- Site \`https://${mapping.site}\`, cloud id \`${mapping.cloud_id}\`, space \`${space}\`.`;
}

function branchesPart({ contract, gates }) {
  const route = contract.new_work_route;
  const types = and(route.applies_to.map((id) => contract.work_types.find((t) => t.id === id).jira_issue_type));
  const rows = contract.bug_routing.flatMap(({ name, routes }) => routes.map((r) => [name, r.severities.join(', '), code(r.base_branch), r.qa_environments.join(', ')]));
  return [
    `- ${types}: \`feature/<KEY>-<slug>\` from ${code(route.base_branch)}; QA on ${route.qa_environments.join(', ')}.`,
    '- Bug: the base branch and the QA environments depend on where the bug is found and its severity. A branch cut from `main` is `hotfix/<KEY>-<slug>`; any other is `bugfix/<KEY>-<slug>`.',
    '',
    table(['Found in', 'Severity', 'Base branch', 'QA on'], rows),
    '',
    '- After a QA fail, the next branch of the same item ends with `-r2`, `-r3`…',
    `- Protected branches: ${gates.protected_branches.map(code).join(', ')}.`,
  ].join('\n');
}

function artifactsPart(contract) {
  const by = (createdBy) => (createdBy === 'reporter' ? 'whoever reports it' : createdBy === 'assignee' ? 'the agent on the item' : createdBy.map(code).join(', '));
  return table(
    ['Artifact', 'Template', 'Created by', 'Stored in'],
    contract.artifacts.map((a) => [a.name, `\`.ai-orchestrator/${a.template}\``, by(a.created_by), stored(a.stored_in)]),
  );
}

const PLACES = { git: 'Git', tracker: 'Jira', 'github-pr': 'GitHub', local: 'Local', 'google-drive': 'Google Drive' };

function stored(places) {
  return places
    .map(({ place, path, note }) => (path ? `${PLACES[place]}: ${code(path)}${note ? ` (${note})` : ''}` : `${PLACES[place]}: ${note}`))
    .join('; ');
}

// The value of each agent role in the Agent field, in contract order.
function agentValues(contract) {
  const field = contract.work_item_fields.find(({ id }) => id === 'agent');
  return Object.fromEntries(field.values.map(({ id, name }) => [id, name]));
}

function table(header, rows) {
  return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((row) => `| ${row.join(' | ')} |`)].join('\n');
}

function stripComments(text) {
  return text.replace(/\r\n?/g, '\n').replace(/<!--[\s\S]*?-->\n*/g, (comment) => (/^<!-- render: [\w-]+ -->/.test(comment) ? comment : '')).trim();
}

function finish(text) {
  return `${text.replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const code = (text) => `\`${text}\``;
const and = (items) => (items.length <= 1 ? items.join('') : `${items.slice(0, -1).join(', ')} and ${items.at(-1)}`);
const circled = (number) => String.fromCharCode(0x2460 + number - 1);
