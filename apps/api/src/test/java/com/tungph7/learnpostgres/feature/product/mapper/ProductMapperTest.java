package com.tungph7.learnpostgres.feature.product.mapper;

import static org.assertj.core.api.Assertions.assertThat;

import java.lang.reflect.Field;
import java.math.BigDecimal;
import java.util.UUID;

import org.junit.jupiter.api.Test;
import org.mapstruct.factory.Mappers;

import com.tungph7.learnpostgres.common.domain.BaseEntity;
import com.tungph7.learnpostgres.feature.product.domain.Product;
import com.tungph7.learnpostgres.feature.product.dto.CreateProductRequest;
import com.tungph7.learnpostgres.feature.product.dto.ProductResponse;

class ProductMapperTest {

  private final ProductMapper mapper = Mappers.getMapper(ProductMapper.class);

  @Test
  void toEntity_maps_all_fields_from_request() {
    CreateProductRequest req =
        new CreateProductRequest("Test Book", "test-book", new BigDecimal("19.99"), "desc");

    Product entity = mapper.toEntity(req);

    assertThat(entity.getName()).isEqualTo("Test Book");
    assertThat(entity.getSlug()).isEqualTo("test-book");
    assertThat(entity.getPrice()).isEqualByComparingTo("19.99");
    assertThat(entity.getDescription()).isEqualTo("desc");
    assertThat(entity.getId()).isNull(); // id is generated by JPA
  }

  @Test
  void toResponse_maps_business_fields_from_entity() {
    // id and auditing fields (createdAt) are only set by JPA/Hibernate;
    // this unit test injects id via reflection (BaseEntity.setId is package-private).
    Product p = new Product("X", "x", new BigDecimal("1.00"), null);
    UUID id = UUID.fromString("0193c1f4-7b9a-7a3c-8d2e-aa1c98dead00");
    setFieldViaReflection(p, "id", id);

    ProductResponse resp = mapper.toResponse(p);

    assertThat(resp.id()).isEqualTo(id);
    assertThat(resp.name()).isEqualTo("X");
    assertThat(resp.slug()).isEqualTo("x");
    assertThat(resp.price()).isEqualByComparingTo("1.00");
    assertThat(resp.description()).isNull();
  }

  /** Test-only helper: sets a private/package-private field on BaseEntity (id, audit fields). */
  static void setFieldViaReflection(Object target, String fieldName, Object value) {
    try {
      Field f = BaseEntity.class.getDeclaredField(fieldName);
      f.setAccessible(true);
      f.set(target, value);
    } catch (NoSuchFieldException | IllegalAccessException e) {
      throw new RuntimeException("Failed to set field " + fieldName, e);
    }
  }
}
