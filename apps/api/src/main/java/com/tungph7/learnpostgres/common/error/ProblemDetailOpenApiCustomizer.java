package com.tungph7.learnpostgres.common.error;

import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.stereotype.Component;

import io.swagger.v3.oas.models.headers.Header;
import io.swagger.v3.oas.models.media.ArraySchema;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.IntegerSchema;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.parameters.Parameter;
import io.swagger.v3.oas.models.responses.ApiResponse;

@Component
public class ProblemDetailOpenApiCustomizer implements OpenApiCustomizer {

  private static final String CORRELATION_ID_HEADER = "X-Correlation-Id";
  private static final String PROBLEM_JSON = "application/problem+json";
  private static final String PROBLEM_REF = "#/components/schemas/ProblemDetail";
  private static final int EXAMPLE_NOT_FOUND_STATUS = 404;
  private static final int MAX_CORRELATION_ID_LENGTH = 128;

  @Override
  public void customise(io.swagger.v3.oas.models.OpenAPI openApi) {
    openApi.getComponents().addSchemas("ProblemDetail", buildProblemSchema());

    ApiResponse badRequest = buildProblemResponse("Bad Request — validation or malformed input");
    ApiResponse internal = buildProblemResponse("Internal Server Error");
    Header correlationHeader = buildCorrelationHeader();

    openApi
        .getPaths()
        .forEach(
            (path, item) ->
                item.readOperations()
                    .forEach(op -> applyToOperation(op, badRequest, internal, correlationHeader)));
  }

  private static Schema<?> buildProblemSchema() {
    return new ObjectSchema()
        .name("ProblemDetail")
        .description("RFC 7807 problem details with extensions")
        .addProperty(
            "type",
            new StringSchema()
                .format("uri")
                .example("https://docs.example.com/errors/PRODUCT_NOT_FOUND"))
        .addProperty("title", new StringSchema().example("Product not found"))
        .addProperty("status", new IntegerSchema().example(EXAMPLE_NOT_FOUND_STATUS))
        .addProperty("detail", new StringSchema().example("Product with id '...' not found."))
        .addProperty(
            "instance",
            new StringSchema().format("uri-reference").example("/api/products/0193c1f4-..."))
        .addProperty("code", new StringSchema().example("PRODUCT_NOT_FOUND"))
        .addProperty("timestamp", new StringSchema().format("date-time"))
        .addProperty("correlationId", new StringSchema().format("uuid"))
        .addProperty(
            "errors",
            new ArraySchema()
                .items(
                    new ObjectSchema()
                        .addProperty("field", new StringSchema())
                        .addProperty("rejectedValue", new ObjectSchema())
                        .addProperty("message", new StringSchema())));
  }

  private static ApiResponse buildProblemResponse(String description) {
    return new ApiResponse()
        .description(description)
        .content(
            new Content()
                .addMediaType(
                    PROBLEM_JSON, new MediaType().schema(new Schema<>().$ref(PROBLEM_REF))));
  }

  private static Header buildCorrelationHeader() {
    return new Header()
        .description(
            "Correlation ID propagated/generated by server. "
                + "Send same header in next requests to chain logs.")
        .schema(new StringSchema().format("uuid").example("0193c200-aaaa-7000-8000-aaa000000001"));
  }

  private static void applyToOperation(
      io.swagger.v3.oas.models.Operation op,
      ApiResponse badRequest,
      ApiResponse internal,
      Header correlationHeader) {
    op.getResponses().addApiResponse("400", badRequest);
    op.getResponses().addApiResponse("500", internal);
    op.getResponses()
        .forEach(
            (status, resp) -> {
              if (resp.getHeaders() == null
                  || !resp.getHeaders().containsKey(CORRELATION_ID_HEADER)) {
                resp.addHeaderObject(CORRELATION_ID_HEADER, correlationHeader);
              }
            });
    Parameter inboundCorr =
        new Parameter()
            .in("header")
            .name(CORRELATION_ID_HEADER)
            .required(false)
            .description("Optional. If absent, server generates a new UUID.")
            .schema(new StringSchema().maxLength(MAX_CORRELATION_ID_LENGTH));
    if (op.getParameters() == null
        || op.getParameters().stream().noneMatch(p -> CORRELATION_ID_HEADER.equals(p.getName()))) {
      op.addParametersItem(inboundCorr);
    }
  }
}
