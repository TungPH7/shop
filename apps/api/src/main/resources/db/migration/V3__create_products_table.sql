-- =====================================================================
-- V3__create_products_table.sql
-- Create the first business table: app.products.
--   - PK is UUIDv7 (DEFAULT app.gen_uuid_v7() — fallback for inserts that
--     bypass JPA; JPA itself generates the id in @PrePersist).
--   - Five audit columns (created_at, updated_at, created_by, updated_by,
--     version) managed by BaseEntity — DEFAULT values are safe for
--     non-JPA inserts.
--   - A BEFORE UPDATE trigger calls app.set_updated_at() (from V2),
--     guaranteeing updated_at is always fresh even when UPDATE bypasses
--     JPA.
--
-- Preconditions:
--   - V1 (init) has run: schema 'app' exists, 4 extensions active.
--   - V2 (app helpers) has run: app.gen_uuid_v7(), app.set_updated_at().
--
-- Note on schema qualification:
--   The JDBC URL sets 'currentSchema=app', so Flyway runs with
--   search_path = 'app' only (NOT including 'public'). Any type or
--   function that lives outside schema 'app' must be qualified
--   explicitly — e.g. `public.citext`, because the citext extension is
--   installed into schema 'public' in V1. Built-in types (VARCHAR,
--   TIMESTAMPTZ, ...) live in pg_catalog and are always implicitly on
--   the search_path, so they need no qualification.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Create the table
-- ---------------------------------------------------------------------
CREATE TABLE app.products (
    -- PK
    id              UUID            PRIMARY KEY DEFAULT app.gen_uuid_v7(),

    -- Business columns
    name            VARCHAR(255)    NOT NULL,
    slug            public.CITEXT   NOT NULL,         -- citext lives in schema public; qualify it
    price           NUMERIC(12, 2)  NOT NULL,
    description     TEXT,

    -- Audit columns (managed by BaseEntity — DEFAULTs act as a non-JPA fallback)
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_by      VARCHAR(64)     NOT NULL DEFAULT 'system',
    updated_by      VARCHAR(64)     NOT NULL DEFAULT 'system',
    version         BIGINT          NOT NULL DEFAULT 0,

    -- Business constraints
    CONSTRAINT products_price_non_negative CHECK (price >= 0),
    CONSTRAINT products_slug_unique        UNIQUE (slug)
);

-- ---------------------------------------------------------------------
-- 2. Comments — inline documentation
-- ---------------------------------------------------------------------
COMMENT ON TABLE  app.products              IS 'Catalog product — first business entity, used to verify the BaseEntity + auditing + trigger pipeline.';
COMMENT ON COLUMN app.products.id           IS 'UUIDv7 (RFC 9562 §5.7) — generated by Java @PrePersist or the DB DEFAULT app.gen_uuid_v7().';
COMMENT ON COLUMN app.products.slug         IS 'URL-friendly identifier, case-insensitive (public.citext). UNIQUE.';
COMMENT ON COLUMN app.products.price        IS 'Price in USD, numeric(12,2). Never use float/double for money.';
COMMENT ON COLUMN app.products.created_at   IS 'When the row was created. JPA @CreatedDate. DEFAULT now() acts as a fallback.';
COMMENT ON COLUMN app.products.updated_at   IS 'When the row was last updated. JPA @LastModifiedDate plus the app.set_updated_at() trigger (defense-in-depth).';
COMMENT ON COLUMN app.products.version      IS 'Optimistic locking @Version. Hibernate injects WHERE version=? in UPDATE statements.';

-- ---------------------------------------------------------------------
-- 3. Indexes
-- ---------------------------------------------------------------------
-- The UNIQUE constraint above implicitly creates a unique index on slug; no separate CREATE INDEX needed.
--
-- Index on created_at (descending) to support the common "list most recent products" query.
-- DESC so the index matches ORDER BY created_at DESC LIMIT N.
CREATE INDEX idx_products_created_at_desc
    ON app.products (created_at DESC);

-- ---------------------------------------------------------------------
-- 4. Trigger: attach app.set_updated_at() (from V2) for BEFORE UPDATE
-- ---------------------------------------------------------------------
-- Guarantees updated_at is always refreshed on UPDATE, including when:
--   - The UPDATE goes through JPQL @Modifying (which bypasses @LastModifiedDate).
--   - A native query is used.
--   - Someone runs UPDATE directly via psql.
--   - A migration updates data in place.
CREATE TRIGGER trg_products_set_updated_at
    BEFORE UPDATE ON app.products
    FOR EACH ROW
    EXECUTE FUNCTION app.set_updated_at();

COMMENT ON TRIGGER trg_products_set_updated_at ON app.products IS
    'Defense-in-depth for updated_at: any UPDATE (JPA or direct SQL) sets updated_at = now().';

-- ---------------------------------------------------------------------
-- 5. Log
-- ---------------------------------------------------------------------
INSERT INTO app._app_migration_log (migration_name, notes)
VALUES (
    'V3__create_products_table',
    'Created app.products with UUIDv7 PK, 5 audit columns, public.citext slug UNIQUE, '
    'numeric(12,2) price CHECK >= 0, trigger trg_products_set_updated_at calling app.set_updated_at().'
);
